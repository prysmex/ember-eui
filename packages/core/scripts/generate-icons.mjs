/**
 * Generates, from vendor/icon/svgs (built by @svg-jar/plugin:
 * `?unsafe-inline` imports become components rendering the inline svg):
 *
 * - src/icons/<type>.ts: one public module per EUI icon type
 *   (`@ember-eui/core/icons/<type>`), whose default export is its
 *   component, for apps registering icons up front (registerIcons).
 * - src/-private/icons.ts: a map from every type to a dynamic import of its
 *   module, so each icon is its own chunk and apps only download the icons
 *   they render. The icon loader imports the map itself with the first icon
 *   that has to load.
 * - src/-private/icon-data.ts: what EuiIcon needs up front: `empty`
 *   (rendered while an icon loads) and the svgs' data-type attributes.
 *
 * The icon names come from `typeToPathMap` in
 * src/utils/css-mappings/eui-icon.ts, which stays the source of truth. Its
 * values are svg paths relative to vendor/icon/svgs, without `.svg` (e.g.
 * `tokens/token_alias`); aliases share their target's svg, and so its chunk.
 *
 * Re-run after adding or renaming icons (scripts/update-eui-icons.mjs
 * rewrites the map from upstream EUI):
 *   node scripts/generate-icons.mjs
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'vendor/icon/svgs');
const mappingFile = join(root, 'src/utils/css-mappings/eui-icon.ts');
const outFile = join(root, 'src/-private/icons.ts');
const dataFile = join(root, 'src/-private/icon-data.ts');
const iconsDir = join(root, 'src/icons');

const source = readFileSync(mappingFile, 'utf8');
const start = source.indexOf('export const typeToPathMap = {');
const block = source.slice(start, source.indexOf('};', start));
// the map repeats some keys; as in JavaScript, the last one wins
const entries = [
  ...new Map(
    [...block.matchAll(/^\s+(\w+|'[^']+'):\s*'([^']+)'/gm)].map(([, key, file]) => [
      key.replace(/'/g, ''),
      file
    ])
  )
];

if (entries.length === 0) {
  throw new Error(`Could not read typeToPathMap from ${mappingFile}`);
}

const lines = [];
const modules = [];
let emptySpecifier;
// @svg-jar/plugin's runtime only keeps viewBox/width/height on the root
// <svg>. EUI's CSS targets `[data-type=logoElastic]`, so root data-type
// attributes are collected here and re-applied by EuiIcon.
const dataTypes = [];

for (const [type, fileName] of entries) {
  const file = join(svgDir, `${fileName}.svg`);

  if (!existsSync(file)) {
    throw new Error(`No svg found for icon "${type}" (${fileName}.svg)`);
  }

  const specifier = (from) => `${relative(from, file).split(sep).join('/')}?unsafe-inline`;

  if (type === 'empty') emptySpecifier = specifier(dirname(outFile));

  lines.push(`  ${JSON.stringify(type)}: () => import('../icons/${type}.ts')`);
  modules.push([
    type,
    `// GENERATED by scripts/generate-icons.mjs, do not edit by hand.
import icon from '${specifier(iconsDir)}';

import type { EuiIconComponent } from '../-private/icon-data.ts';

/**
 * The \`${type}\` EUI icon. Register it to render it without loading it
 * first: \`registerIcons({ ${JSON.stringify(type).slice(1, -1).match(/^[A-Za-z_$][\w$]*$/) ? type : `'${type}': icon`} })\` from
 * \`@ember-eui/core/utils/preload-icons\`.
 */
const component: EuiIconComponent = icon;

export default component;
`
  ]);

  const rootTag = readFileSync(file, 'utf8').match(/<svg\b[^>]*>/)?.[0] ?? '';
  const dataType = rootTag.match(/\sdata-type="([^"]*)"/)?.[1];

  if (dataType) {
    dataTypes.push(`  ${JSON.stringify(type)}: ${JSON.stringify(dataType)}`);
  }
}

if (!emptySpecifier) {
  throw new Error('typeToPathMap has no "empty" icon, needed as the placeholder');
}

rmSync(iconsDir, { recursive: true, force: true });
mkdirSync(iconsDir, { recursive: true });

for (const [type, code] of modules) {
  writeFileSync(join(iconsDir, `${type}.ts`), code);
}

writeFileSync(
  dataFile,
  `// GENERATED by scripts/generate-icons.mjs, do not edit by hand.
import empty from '${emptySpecifier}';

import type { typeToPathMap } from '../utils/css-mappings/eui-icon.ts';
import type { ComponentLike } from '@glint/template';

export type EuiIconComponent = ComponentLike<{
  Element: SVGSVGElement;
  Blocks: { default: [] };
}>;

export type EuiIconLoader = () => Promise<{ default: EuiIconComponent }>;

/** Rendered while an icon loads. */
export const emptyIcon: EuiIconComponent = empty;

/** \`data-type\` attributes from the source svgs, used by EUI's CSS. */
export const iconDataTypes: Partial<
  Record<keyof typeof typeToPathMap, string>
> = {
${dataTypes.join(',\n')}
};
`
);

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-icons.mjs, do not edit by hand.
import type { EuiIconLoader } from './icon-data.ts';
import type { typeToPathMap } from '../utils/css-mappings/eui-icon.ts';

export type { EuiIconComponent, EuiIconLoader } from './icon-data.ts';

const iconLoaders: Record<keyof typeof typeToPathMap, EuiIconLoader> = {
${lines.join(',\n')}
};

export default iconLoaders;
`
);

console.log(`wrote ${entries.length} icons`);
