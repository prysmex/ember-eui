/**
 * Generates src/-private/languages.ts: a map from every language refractor
 * highlights (names and aliases) to a loader for the refractor language
 * that defines it. Each language is a dynamic import, so it ends up in its
 * own chunk and apps only download the languages they highlight; the ones
 * `refractor/core` already has (markup/html/xml/svg, css, clike, js) need no
 * loading.
 *
 * Language files declare only some of their aliases, so each one is
 * registered (after the languages it requires) and the names it adds are
 * recorded.
 *
 * Re-run after upgrading refractor:
 *   node scripts/generate-languages.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/-private/languages.ts');
const require = createRequire(join(root, 'package.json'));

const refractor = require('refractor/core');
const langDir = join(dirname(require.resolve('refractor/core')), 'lang');
const files = readdirSync(langDir)
  .filter((file) => file.endsWith('.js'))
  .sort();

const builtIn = new Set(refractor.listLanguages());
const fileOf = new Map();
const registered = new Set();

function register(file) {
  if (registered.has(file)) return;
  registered.add(file);

  // the languages it builds on register first, so their names are theirs
  const source = readFileSync(join(langDir, file), 'utf8');

  for (const [, dependency] of source.matchAll(/require\('\.\/([\w-]+\.js)'\)/g)) {
    register(dependency);
  }

  const before = new Set(refractor.listLanguages());

  refractor.register(require(join(langDir, file)));

  for (const name of refractor.listLanguages()) {
    if (!before.has(name) && !builtIn.has(name)) fileOf.set(name, file);
  }
}

files.forEach(register);

const entries = [...fileOf]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, file]) => `  ${JSON.stringify(name)}: () => import('refractor/lang/${file}'),`);

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-languages.mjs, do not edit by hand.
import type { RefractorSyntax } from 'refractor/core';

export type LanguageLoader = () => Promise<{ default: RefractorSyntax }>;

/** Languages \`refractor/core\` highlights without loading anything. */
export const BUILT_IN_LANGUAGES: readonly string[] = ${JSON.stringify([...builtIn])};

/** Every other language refractor highlights, by name and alias. */
const languageLoaders: Record<string, LanguageLoader> = {
${entries.join('\n')}
};

export default languageLoaders;
`
);

console.log(`Wrote ${fileOf.size} languages (+${builtIn.size} built in) to ${outFile}`);
