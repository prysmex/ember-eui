/**
 * Port of EUI 123.1.0 `services/copy/tabular_copy.tsx`: visually hidden
 * marker characters placed in tabular content are turned into tabs and
 * newlines when a selection is copied, so it pastes cleanly into a
 * spreadsheet. The markers are rendered by the grid as
 * `<span class="euiScreenReaderOnly" aria-hidden="true" data-tabular-copy-marker>`.
 */

// Special visually hidden unicode characters that we use to manually clean content
// and force our own newlines/horizontal tabs
export const CHARS = {
  NEWLINE: '↵',
  TAB: '↦',
  // Use multiple characters to reduce the chances of consumers also using these characters
  TABULAR_CONTENT_BOUND: '𐘂𐘂',
  NO_COPY_BOUND: '✄𐘗'
} as const;

/**
 * Finds all content between two no-copy bounds (the `u` flag, unlike
 * upstream, reads the bound's astral character as one code point).
 */
export const noCopyBoundsRegex = new RegExp(
  `${CHARS.NO_COPY_BOUND}[^${CHARS.NO_COPY_BOUND}]*${CHARS.NO_COPY_BOUND}`,
  'gsu'
);

const hasCharsToReplace = (text: string): boolean => {
  for (const char of Object.values(CHARS)) {
    if (text.indexOf(char) >= 0) return true;
  }
  return false;
};

/**
 * Strips existing newlines and replaces the hidden characters with the
 * spacing needed to paste cleanly into a spreadsheet. Registered on the
 * document (a static handler, so it is only added once).
 */
export function onTabularCopy(event: ClipboardEvent): void {
  if (!event.clipboardData) return;
  const selectedText = window.getSelection()?.toString();
  if (!selectedText || !hasCharsToReplace(selectedText)) return;
  const amendedText = selectedText
    .split(CHARS.TABULAR_CONTENT_BOUND)
    .map((text) =>
      hasCharsToReplace(text)
        ? text
            .replace(/\r?\n/g, '') // remove all other newlines generated by content or block display
            .replaceAll(CHARS.NEWLINE, '\n') // insert newline for each table/grid row
            .replace(/\t/g, '') // remove tabs generated by content or automatically by <td> elements
            .replaceAll(CHARS.TAB, '\t') // insert horizontal tab for each table/grid cell
            .replace(noCopyBoundsRegex, '') // remove text that should not be copied (e.g. screen reader instructions)
        : text
    )
    .join('');
  event.clipboardData.setData('text/plain', amendedText);
  event.preventDefault();
}
