/**
 * Generates tests/addon-app-modules.ts
 *
 * Some dependencies still look things up by name through the app resolver
 * (ember-power-select 8 uses loose-mode templates like `<PowerSelect>` and
 * `{{did-insert}}`; ember-keyboard needs `service:keyboard`). A real app gets
 * those from each v2 addon's `ember-addon.app-js` re-exports. Our test app
 * uses ember-strict-application-resolver, so we register the same modules
 * explicitly, importing them by package name.
 *
 * Re-run after changing these dependencies:
 *   node tests/generate-addon-app-modules.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ADDONS = [
  'ember-power-select',
  'ember-basic-dropdown',
  'ember-truth-helpers',
  '@ember/render-modifiers',
  'ember-keyboard',
  // not used by core directly; ember-power-select 8 resolves {{assign}} by name
  'ember-assign-helper'
];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));

const imports = [];
const entries = [];

for (const addon of ADDONS) {
  const pkgDir = dirname(require.resolve(`${addon}/addon-main.js`));
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

  for (const [appPath, file] of Object.entries(pkg['ember-addon']['app-js'])) {
    const source = readFileSync(join(pkgDir, file), 'utf8');
    const match = source.match(/export\s*\{\s*default\s*\}\s*from\s*["']([^"']+)["']/);

    if (!match) {
      throw new Error(`Unexpected app-js re-export in ${addon}/${file}:\n${source}`);
    }

    const name = `m${imports.length}`;
    imports.push(`import ${name} from '${match[1]}';`);
    entries.push(`  '${appPath.replace(/\.js$/, '')}': ${name}`);
  }
}

const output = `// GENERATED by tests/generate-addon-app-modules.mjs, do not edit by hand.
/* eslint-disable */
// @ts-nocheck
${imports.join('\n')}

export default {
${entries.join(',\n')}
};
`;

writeFileSync(join(root, 'tests/addon-app-modules.ts'), output);
console.log(`wrote ${entries.length} modules`);
